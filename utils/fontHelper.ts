export const analyzeFontFile = async (file: File): Promise<FontDefinition> => {
    return new Promise((resolve, reject) => {
        const reader = new FileReader();
        reader.onload = (e) => {
            const buffer = e.target?.result as ArrayBuffer;
            if (!buffer) {
                reject(new Error("Failed to read file"));
                return;
            }

            try {
                // @ts-ignore - opentype might be loaded as default or named export depending on environment
                const font = parse ? parse(buffer) : window.opentype.parse(buffer);
                
                // 1. Get Name
                let fontName = file.name.split('.')[0];
                if (font.names.fontFamily && font.names.fontFamily.en) {
                    fontName = font.names.fontFamily.en;
                } else if (font.names.fullName && font.names.fullName.en) {
                    fontName = font.names.fullName.en;
                }

                // 2. Detect Language Support
                const tags: ('tc' | 'sc' | 'en' | 'ja' | 'ko')[] = [];
                const detectedLanguages: string[] = [];

                // --- Chinese (Simplified vs Traditional) ---
                let scHits = 0;
                let tcHits = 0;
                let cjkTotal = 0;

                DISTINCT_PAIRS.forEach(([scChar, tcChar]) => {
                    const hasSC = font.charToGlyphIndex(scChar) > 0;
                    const hasTC = font.charToGlyphIndex(tcChar) > 0;
                    if (hasSC) scHits++;
                    if (hasTC) tcHits++;
                    cjkTotal++;
                });

                const scPercent = cjkTotal > 0 ? (scHits / cjkTotal) : 0;
                const tcPercent = cjkTotal > 0 ? (tcHits / cjkTotal) : 0;
                const CJK_THRESHOLD = 0.5;

                if (tcPercent > CJK_THRESHOLD) {
                    tags.push('tc');
                    detectedLanguages.push('Traditional Chinese');
                }
                if (scPercent > CJK_THRESHOLD) {
                    tags.push('sc');
                    detectedLanguages.push('Simplified Chinese');
                }

                // --- English ---
                let enHits = 0;
                for (const char of ENGLISH_CHARS) {
                     if (font.charToGlyphIndex(char) > 0) enHits++;
                }
                if (enHits / ENGLISH_CHARS.length > 0.9) {
                     tags.push('en');
                     detectedLanguages.push('English');
                }

                // --- Japanese ---
                let jaHits = 0;
                for (const char of JAPANESE_CHARS) {
                    if (font.charToGlyphIndex(char) > 0) jaHits++;
                }
                // Japanese fonts should support most Kana
                if (jaHits / JAPANESE_CHARS.length > 0.8) {
                    tags.push('ja');
                    detectedLanguages.push('Japanese');
                }

                // --- Korean ---
                let koHits = 0;
                for (const char of KOREAN_CHARS) {
                     if (font.charToGlyphIndex(char) > 0) koHits++;
                }
                if (koHits / KOREAN_CHARS.length > 0.8) {
                    tags.push('ko');
                    detectedLanguages.push('Korean');
                }

                // Construct description
                let description = "Detected: ";
                if (detectedLanguages.length > 0) {
                    description += detectedLanguages.join(", ");
                } else {
                    description += "Limited or Symbols";
                }

                // 3. Resolve
                const fontDef: FontDefinition = {
                    name: fontName,
                    family: fontName, 
                    category: 'display', 
                    tags: tags,
                    description: description,
                    isCustom: true
                };

                resolve(fontDef);
            } catch (err) {
                console.error("Font analysis error:", err);
                reject(err);
            }
        };
        reader.onerror = reject;
        reader.readAsArrayBuffer(file);
    });
};

export const loadFontFace = async (fontName: string, data: ArrayBuffer): Promise<void> => {
    const fontFace = new FontFace(fontName, data);
    await fontFace.load();
    document.fonts.add(fontFace);
};